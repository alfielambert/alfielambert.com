#!/usr/bin/env node
// Bakes content/writing/*.mdx into static, build-time-generated modules.
//
// Two separate Cloudflare Workers (workerd) incompatibilities motivate this:
//
// 1. Workers have no real filesystem at runtime, even with the nodejs_compat
//    flag — fs.readdirSync/readFileSync against content/writing silently
//    return nothing there, regardless of what Next's output file tracing
//    includes in the build.
// 2. next-mdx-remote/rsc compiles MDX to a component at request time via
//    @mdx-js/mdx's runtime `evaluate`, which uses `new Function(...)`.
//    Workers disallow code generation from strings entirely, so this throws
//    "EvalError: Code generation from strings disallowed for this context".
//
// Reading and compiling the MDX files here, during a real Node build step,
// and emitting plain ES modules (metadata as data, MDX bodies as compiled
// JS using react/jsx-runtime calls — no eval) turns both into a normal
// part of the JS module graph, which works identically in `next dev`,
// `next build`, and the deployed Worker.
import fs from 'node:fs'
import path from 'node:path'
import matter from 'gray-matter'
import { compile } from '@mdx-js/mdx'
import remarkGfm from 'remark-gfm'

const WRITING_DIR = path.join(process.cwd(), 'content/writing')
const GENERATED_DIR = path.join(process.cwd(), 'src/lib/generated')
const MDX_OUT_DIR = path.join(GENERATED_DIR, 'mdx')
const INDEX_FILE = path.join(GENERATED_DIR, 'writing-content.generated.ts')

const files = fs.existsSync(WRITING_DIR)
  ? fs.readdirSync(WRITING_DIR).filter((f) => f.endsWith('.mdx'))
  : []

fs.mkdirSync(MDX_OUT_DIR, { recursive: true })

const entries = []

for (const filename of files) {
  const raw = fs.readFileSync(path.join(WRITING_DIR, filename), 'utf-8')
  const { data, content } = matter(raw)
  const slug = data.slug || filename.replace(/\.mdx$/, '')

  const compiled = await compile(content, {
    outputFormat: 'program',
    remarkPlugins: [remarkGfm],
  })

  fs.writeFileSync(path.join(MDX_OUT_DIR, `${slug}.js`), String(compiled))

  entries.push({ slug, filename, frontmatter: data, content })
}

const imports = entries
  .map((e, i) => `import MDXContent${i} from './mdx/${e.slug}.js'`)
  .join('\n')

const postsArray = entries
  .map(
    (e, i) => `  {
    slug: ${JSON.stringify(e.slug)},
    filename: ${JSON.stringify(e.filename)},
    frontmatter: ${JSON.stringify(e.frontmatter)},
    content: ${JSON.stringify(e.content)},
    MDXContent: MDXContent${i},
  },`
  )
  .join('\n')

const output = `// AUTO-GENERATED by scripts/generate-writing-content.mjs — do not edit by hand.
// Regenerated on every \`npm run dev\` / \`npm run build\`.
import type { ComponentType } from 'react'
${imports}

export interface GeneratedWritingPost {
  slug: string
  filename: string
  frontmatter: Record<string, unknown>
  content: string
  MDXContent: ComponentType<{ components?: Record<string, unknown> }>
}

export const generatedWritingPosts: GeneratedWritingPost[] = [
${postsArray}
]
`

fs.writeFileSync(INDEX_FILE, output)
console.log(`Generated ${INDEX_FILE} (${entries.length} post${entries.length === 1 ? '' : 's'})`)
